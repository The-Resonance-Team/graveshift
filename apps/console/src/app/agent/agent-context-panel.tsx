import { Button } from '@astryxdesign/core/Button';
import { HStack, VStack } from '@astryxdesign/core/Layout';
import { Markdown } from '@astryxdesign/core/Markdown';
import { Section } from '@astryxdesign/core/Section';
import { Text } from '@astryxdesign/core/Text';
import { Token } from '@astryxdesign/core/Token';
import { Toolbar } from '@astryxdesign/core/Toolbar';

import type { PlannedArtifact } from '../../fixtures/agent';

const TOOLBAR_DIVIDERS: Array<'top' | 'bottom'> = ['bottom'];

export function AgentContextPanel({
  artifact,
  onSourceMessage,
  onClose,
  showClose,
}: {
  artifact: PlannedArtifact;
  onSourceMessage: () => void;
  onClose: () => void;
  showClose: boolean;
}) {
  const renderStart = () => (
    <VStack gap={0}>
      <Text type="label" weight="semibold">
        {artifact.title}
      </Text>
      <Text type="supporting" color="secondary">
        Sample artifact, linked to conversation
      </Text>
    </VStack>
  );

  const renderEnd = () =>
    showClose ? <Button label="Close panel" size="sm" onClick={onClose} /> : null;

  return (
    <VStack gap={0} height="100%">
      <Toolbar
        label="Artifact actions"
        dividers={TOOLBAR_DIVIDERS}
        startContent={renderStart()}
        endContent={renderEnd()}
      />
      <Section variant="transparent" padding={4}>
        <VStack gap={4}>
          <HStack gap={2} wrap="wrap">
            <Token label={artifact.filename} />
            <Token label={artifact.status === 'ready' ? 'Sample ready' : 'Unavailable'} />
          </HStack>
          <Text color="secondary">{artifact.summary}</Text>
          <Button label="Go to source message" size="sm" onClick={onSourceMessage} />
          <Markdown density="compact" headingLevelStart={3}>
            {artifact.content}
          </Markdown>
          <Text type="supporting" color="secondary">
            Source: {artifact.sourceMessageId} in the sample conversation. Not generated by an
            Agent.
          </Text>
        </VStack>
      </Section>
    </VStack>
  );
}
